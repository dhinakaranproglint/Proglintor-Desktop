'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('agent', {
  rangeView: (range, anchor) => ipcRenderer.invoke('usage:range', range, anchor),
  appDetail: (id, day) => ipcRenderer.invoke('usage:detail', id, day),
  installed: (refresh = false) => ipcRenderer.invoke('apps:installed', refresh),
  icon: (id, path) => ipcRenderer.invoke('icon:get', id, path),
  status: () => ipcRenderer.invoke('status:get'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  swiftCheck: () => ipcRenderer.invoke('swift:check'),
  swiftImport: () => ipcRenderer.invoke('swift:import'),
  exportCSV: () => ipcRenderer.invoke('data:export'),
  clearData: () => ipcRenderer.invoke('data:clear'),
  openDataFolder: () => ipcRenderer.invoke('data:folder'),
  openApp: (path) => ipcRenderer.invoke('app:open', path),
  revealApp: (path) => ipcRenderer.invoke('app:reveal', path),
  showWindow: () => ipcRenderer.invoke('window:show'),
  // Proglint organization
  orgStatus: () => ipcRenderer.invoke('org:status'),
  enroll: (code) => ipcRenderer.invoke('org:enroll', code),
  syncNow: () => ipcRenderer.invoke('org:sync'),
  // Install assistant
  software: {
    catalogue: () => ipcRenderer.invoke('sw:catalogue'),
    list: () => ipcRenderer.invoke('sw:list'),
    preview: (prompt) => ipcRenderer.invoke('sw:preview', prompt),
    assist: (message, history) => ipcRenderer.invoke('sw:assist', message, history),
    submit: (prompt, key, reinstall) => ipcRenderer.invoke('sw:submit', prompt, key, reinstall === true),
    confirm: (id) => ipcRenderer.invoke('sw:confirm', id),
    cancel: (id) => ipcRenderer.invoke('sw:cancel', id),
  },
  // Orbit, the personal work companion
  orbit: {
    briefing: () => ipcRenderer.invoke('orbit:briefing'),
    chat: (messages, agentName) => ipcRenderer.invoke('orbit:chat', messages, agentName),
    tasks: () => ipcRenderer.invoke('orbit:tasks'),
    updateTask: (id, patch) => ipcRenderer.invoke('orbit:task', id, patch),
    achievements: () => ipcRenderer.invoke('orbit:achievements'),
    timesheet: (month) => ipcRenderer.invoke('orbit:timesheet', month),
    timesheetSummary: (period, start) => ipcRenderer.invoke('orbit:timesheet:summary', period, start),
    timesheetCsv: (month) => ipcRenderer.invoke('orbit:timesheet:csv', month),
    nominate: (body) => ipcRenderer.invoke('orbit:nominate', body),
    certificate: (id) => ipcRenderer.invoke('orbit:certificate', id),
    saveCertificate: (id) => ipcRenderer.invoke('orbit:certificate:save', id),
    persona: () => ipcRenderer.invoke('orbit:persona:get'),
    setPersona: (patch) => ipcRenderer.invoke('orbit:persona:set', patch),
    identity: () => ipcRenderer.invoke('orbit:identity'),
    poke: () => ipcRenderer.invoke('orbit:poke'),
    greetAct: (what) => ipcRenderer.invoke('orbit:greet:act', what),
    companionLayout: () => ipcRenderer.invoke('orbit:companion:layout'),
    companionHit: (over) => ipcRenderer.invoke('orbit:companion:hit', over === true),
    companionDrag: (phase, dx, dy) => ipcRenderer.invoke('orbit:companion:drag', phase, dx, dy),
    companionOpen: (page) => ipcRenderer.invoke('orbit:companion:open', page),
    companionFocus: (on) => ipcRenderer.invoke('orbit:companion:focus', on === true),
    demo: (kind) => ipcRenderer.invoke('orbit:demo', kind),
    onQuick: (fn) => ipcRenderer.on('agent:orbit-quick', () => fn()),
    companionMenu: () => ipcRenderer.invoke('orbit:companion:menu'),
    onSay: (fn) => ipcRenderer.on('agent:orbit-say', (_e, m) => fn(m)),
    onGreet: (fn) => ipcRenderer.on('agent:orbit-greet', () => fn()),
    checkinAnswer: (id) => ipcRenderer.invoke('orbit:checkin:answer', id),
    onCheckIn: (fn) => ipcRenderer.on('agent:orbit-checkin', (_e, m) => fn(m)),
    onWelcome: (fn) => ipcRenderer.on('agent:orbit-welcome', (_e, m) => fn(m)),
    onLayout: (fn) => ipcRenderer.on('agent:orbit-layout', (_e, l) => fn(l)),
    hide: (minutes) => ipcRenderer.invoke('orbit:hide', minutes),
    show: () => ipcRenderer.invoke('orbit:show'),
    presenting: (on) => ipcRenderer.invoke('orbit:presenting', on),
    care: {
      get: () => ipcRenderer.invoke('orbit:care:get'),
      set: (patch) => ipcRenderer.invoke('orbit:care:set', patch),
      act: (kind, action) => ipcRenderer.invoke('orbit:care:act', kind, action),
      water: () => ipcRenderer.invoke('orbit:care:water'),
      pause: (minutes) => ipcRenderer.invoke('orbit:care:pause', minutes),
      focus: (minutes) => ipcRenderer.invoke('orbit:care:focus', minutes),
      onNudge: (fn) => ipcRenderer.on('agent:orbit-care', (_e, n) => fn(n)),
      onState: (fn) => ipcRenderer.on('agent:orbit-care-state', () => fn()),
    },
    onChange: (fn) => ipcRenderer.on('agent:orbit', () => fn()),
    onPersona: (fn) => ipcRenderer.on('agent:orbit-persona', () => fn()),
  },
  /** An install request changed (approved, progress, finished). */
  onSoftware: (fn) => ipcRenderer.on('agent:software', () => fn()),
  /** A notification asked to open a page. */
  onGoto: (fn) => ipcRenderer.on('agent:goto', (_e, page) => fn(page)),
  // Weekend work check
  warningInfo: () => ipcRenderer.invoke('warning:info'),
  warningSubmit: (answer) => ipcRenderer.invoke('warning:submit', answer),
  warningLater: () => ipcRenderer.invoke('warning:later'),
  warningClose: () => ipcRenderer.invoke('warning:close'),
  quit: () => ipcRenderer.invoke('app:quit'),
  /** Called when the current app/state changes (instant) or periodically (running totals). */
  onNavigate: (fn) => ipcRenderer.on('agent:navigate', () => fn()),
  onUpdate: (fn) => {
    ipcRenderer.on('agent:update', () => fn('update'));
    ipcRenderer.on('agent:tick', () => fn('tick'));
  },
  platform: process.platform,
});
